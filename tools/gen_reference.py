#!/usr/bin/env python3
"""Generate shared/testdata/reference-praytimes.json.

Reference values come from PrayTimes (praytimes.org, `pip install praytimes`),
an implementation independent of Adhan. Both platform test suites compare their
output against this file with a small tolerance, so a regression in either port
(or a mistake in our wrapper) shows up as a mismatch.

Only cases where no high-latitude rule kicks in belong here: PrayTimes and Adhan
handle high latitudes differently by design. Those cases are covered by
property tests in each platform instead.

Usage: python3 tools/gen_reference.py > shared/testdata/reference-praytimes.json
"""
import datetime as dt
import json
from zoneinfo import ZoneInfo

from praytimes import PrayTimes

PLACES = {
    "toronto": (43.6532, -79.3832, "America/Toronto"),
    "kathmandu": (27.7172, 85.3240, "Asia/Kathmandu"),   # +5:45
    "mumbai": (19.0760, 72.8777, "Asia/Kolkata"),        # +5:30
    "sydney": (-33.8688, 151.2093, "Australia/Sydney"),  # southern hemisphere, DST
    "makkah": (21.4225, 39.8262, "Asia/Riyadh"),
}

# (case id prefix, place, our method id, madhab, PrayTimes settings, dates)
CASES = [
    ("toronto-isna", "toronto", "isna", "shafi", {"fajr": 15, "isha": 15},
     ["2026-01-15", "2026-03-07", "2026-03-08", "2026-03-09", "2026-05-15",
      "2026-06-21", "2026-10-31", "2026-11-01", "2026-11-02"]),
    ("toronto-mwl-hanafi", "toronto", "mwl", "hanafi", {"fajr": 18, "isha": 17, "asr": "Hanafi"},
     ["2026-02-18", "2026-05-15", "2026-09-01"]),
    ("toronto-custom12", "toronto", "custom:12:12", "shafi", {"fajr": 12, "isha": 12},
     ["2026-05-15"]),
    ("kathmandu-karachi-hanafi", "kathmandu", "karachi", "hanafi",
     {"fajr": 18, "isha": 18, "asr": "Hanafi"}, ["2026-01-10", "2026-07-10"]),
    ("mumbai-karachi-hanafi", "mumbai", "karachi", "hanafi",
     {"fajr": 18, "isha": 18, "asr": "Hanafi"}, ["2026-04-01", "2026-12-01"]),
    ("sydney-mwl", "sydney", "mwl", "shafi", {"fajr": 18, "isha": 17},
     ["2026-04-04", "2026-04-05", "2026-06-21", "2026-10-04", "2026-12-21"]),
    # 2026-01-15 is outside Ramadan, so Isha is Maghrib + 90.
    ("makkah-ummalqura", "makkah", "ummalqura", "shafi", {"fajr": 18.5, "isha": "90 min"},
     ["2026-01-15", "2026-07-15"]),
]

PRAYERS = ["fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"]


def expected(times, pt_settings):
    # PrayTimes-py's own "maghrib" key comes out ~20 min after sunset in this
    # package, and its "N min" Isha is relative to that. Maghrib is sunset for
    # every method used here, so derive both from sunset.
    out = {p: times[p] for p in PRAYERS}
    out["maghrib"] = times["sunset"]
    isha = str(pt_settings["isha"])
    if isha.endswith(" min"):
        h, m = map(int, times["sunset"].split(":"))
        total = h * 60 + m + int(isha.split()[0])
        out["isha"] = f"{total // 60 % 24:02d}:{total % 60:02d}"
    return out


def main():
    out = []
    for prefix, place, method, madhab, pt_settings, dates in CASES:
        lat, lon, tz = PLACES[place]
        for d in dates:
            date = dt.date.fromisoformat(d)
            # Offset at local noon: every prayer except a pre-2am Isha falls on
            # the noon side of a DST switch.
            noon = dt.datetime(date.year, date.month, date.day, 12, tzinfo=ZoneInfo(tz))
            offset_h = noon.utcoffset().total_seconds() / 3600
            pt = PrayTimes("MWL")
            pt.adjust({"highLats": "None", "asr": "Standard", **pt_settings})
            times = pt.getTimes((date.year, date.month, date.day), (lat, lon), offset_h, 0, "24h")
            out.append({
                "id": f"{prefix}-{d}",
                "latitude": lat,
                "longitude": lon,
                "timeZone": tz,
                "date": d,
                "method": method,
                "madhab": madhab,
                "expected": expected(times, pt_settings),
            })
    print(json.dumps({
        "source": "PrayTimes 2.3.2 (praytimes.org), generated by tools/gen_reference.py",
        "toleranceMinutes": 2,
        "cases": out,
    }, indent=2))


if __name__ == "__main__":
    main()
